# ---- raster + pack ----------------------------------------------------------------------------


def fetch_fonts(cache: Path) -> list:
    files = []
    for family, url in FONT_URLS.items():
        path = cache / url.rsplit("/", 1)[1]
        if not path.exists():
            try:
                with urllib.request.urlopen(url, timeout=30) as resp:
                    path.write_bytes(resp.read())
            except OSError as err:
                print(f"warning: could not fetch {family} ({err}); using a system serif", file=sys.stderr)
                continue
        files.append(str(path))
    return files


def rasterize(markup: str, w: int, h: int, fonts: list) -> np.ndarray:
    png = bytes(resvg_py.svg_to_bytes(svg_string=markup, width=w * SUPER, height=h * SUPER, font_files=fonts))
    return np.asarray(Image.open(io.BytesIO(png)).convert("RGBA"))


def classify(rgba: np.ndarray) -> np.ndarray:
    """3x3-supersampled RGBA -> per-pixel state (0 transparent, 1 white, 2 black)."""
    h, w = rgba.shape[0] // SUPER, rgba.shape[1] // SUPER
    blocks = rgba[: h * SUPER, : w * SUPER].reshape(h, SUPER, w, SUPER, 4).transpose(0, 2, 1, 3, 4)
    blocks = blocks.reshape(h, w, SUPER * SUPER, 4).astype(np.float32)
    opaque = blocks[..., 3] >= 128
    lum = blocks[..., 0] * 0.299 + blocks[..., 1] * 0.587 + blocks[..., 2] * 0.114
    n_opaque = opaque.sum(axis=2)
    dark = opaque & (lum < 128)
    mid = opaque & (lum >= BLACK_L) & (lum <= WHITE_L)
    light = opaque & ~dark
    black_frac = dark.sum(axis=2) / np.maximum(n_opaque, 1)
    mean_light = np.where(light, lum, 0).sum(axis=2) / np.maximum(light.sum(axis=2), 1)
    density = np.clip((WHITE_L - mean_light) / (WHITE_L - BLACK_L), 0, 1) * 16
    ys, xs = np.mgrid[0:h, 0:w]
    dither_black = density > BAYER[ys % 4, xs % 4]
    state = np.where(black_frac >= 0.5, 2, np.where(mid.sum(axis=2) >= 5, np.where(dither_black, 2, 1), 1))
    return np.where(n_opaque * 2 >= SUPER * SUPER, state, 0).astype(np.uint8)


def rle(grid: np.ndarray) -> bytes:
    flat = grid.ravel()
    out = bytearray()
    i, n = 0, len(flat)
    while i < n:
        v, j = flat[i], i + 1
        while j < n and j - i < 64 and flat[j] == v:
            j += 1
        out.append((int(v) << 6) | (j - i - 1))
        i = j
    return bytes(out)


def glyph_grids(fonts: list) -> list:
    """Shared vertical crop (so every glyph has one baseline), tight horizontal crop."""
    grids = [classify(rasterize(glyph(c), GLYPH_CANVAS_W, GLYPH_CANVAS_H, fonts)) for c in GLYPHS]
    grids = [np.where(g == 2, 2, 0).astype(np.uint8) for g in grids]  # ink only
    rows = np.nonzero(np.any(np.stack(grids) > 0, axis=(0, 2)))[0]
    out = []
    for g in grids:
        g = g[rows.min() : rows.max() + 1]
        cols = np.nonzero(g.any(axis=0))[0]
        out.append(np.pad(g[:, cols.min() : cols.max() + 1], ((0, 0), (2, 2))))
    return out


