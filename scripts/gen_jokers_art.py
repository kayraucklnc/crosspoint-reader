CLUB_LOBES = [(0, -0.5), (-0.52, 0.14), (0.52, 0.14)]


def suit(s: int, cx: float, cy: float, size: float, ink: str = B, paper: str = W, sw: float = 3.0) -> str:
    """Suit symbol `size` px tall. Hearts/diamonds are hollow (paper fill, ink outline)."""
    k = size / 2
    if s in (1, 3):
        k2 = max(k - sw / 2, 1)
        d = HEART if s == 1 else DIAMOND
        return (f'<path d="{d}" transform="translate({cx} {cy}) scale({k2})" fill="{paper}" stroke="{ink}" '
                f'stroke-width="{sw / k2}" stroke-linejoin="round"/>')
    if s == 0:
        return f'<path d="{SPADE}" transform="translate({cx} {cy}) scale({k})" fill="{ink}"/>'
    lobes = "".join(f'<circle cx="{x}" cy="{y}" r="0.45"/>' for x, y in CLUB_LOBES)
    return (f'<g transform="translate({cx} {cy}) scale({k})" fill="{ink}">{lobes}'
            f'<circle cx="0" cy="0.02" r="0.3"/><path d="{CLUB_STEM}"/></g>')


def svg(w: int, h: int, body: str) -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">{body}</svg>'


def text(s: str, x: float, baseline: float, cap: float, fill: str = B, family: str = SERIF, squeeze: float = 1.0,
         anchor: str = "middle", extra: str = "") -> str:
    size = cap / CAP
    return (f'<g transform="translate({x} {baseline}) scale({squeeze} 1)"><text x="0" y="0" font-family="{family}" '
            f'font-size="{size:.2f}" text-anchor="{anchor}" fill="{fill}" stroke="{fill}" stroke-width="{cap / 28:.2f}" '
            f'stroke-linejoin="round" {extra}>{s}</text></g>')


def circle_path(cx, cy, r) -> str:
    return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z"


