def card_frame(fill: str = W) -> str:
    return f'<rect x="1" y="1" width="{CARD_W - 2}" height="{CARD_H - 2}" rx="8" fill="{fill}" stroke="{B}" stroke-width="2"/>'


def index(rank: int, s: int) -> str:
    """Top-left rank + suit, and the same rotated 180 degrees bottom-right."""
    squeeze = 0.62 if RANKS[rank] == "10" else 0.9
    one = text(RANKS[rank], 17, 31, 25, squeeze=squeeze) + suit(s, 17, 48, 17, sw=2.6)
    return one + f'<g transform="rotate(180 {CARD_W / 2} {CARD_H / 2})">{one}</g>'


def deco_frame(x0, y0, x1, y1) -> str:
    """Double rule with stepped Art-Deco corners."""
    out = [f'<rect x="{x0 + 0.5}" y="{y0 + 0.5}" width="{x1 - x0 - 1}" height="{y1 - y0 - 1}" fill="none" stroke="{B}" stroke-width="1"/>',
           f'<rect x="{x0 + 3.5}" y="{y0 + 3.5}" width="{x1 - x0 - 7}" height="{y1 - y0 - 7}" fill="none" stroke="{B}" stroke-width="1"/>']
    for cx, cy, dx, dy in ((x0, y0, 1, 1), (x1, y0, -1, 1), (x0, y1, 1, -1), (x1, y1, -1, -1)):
        out.append(f'<path d="M{cx},{cy} h{dx * 9} v{dy * 3} h{-dx * 6} v{dy * 6} h{-dx * 3} Z" fill="{B}"/>')
    return "".join(out)


def number_card(rank: int, s: int) -> str:
    label = RANKS[rank]
    squeeze = 0.6 if label == "10" else 0.95
    body = card_frame() + index(rank, s) + deco_frame(33, 10, 84, 154)
    body += text(label, 58.5, 86, 44, squeeze=squeeze)
    body += suit(s, 58.5, 118, 34, sw=4)
    # small pips as a count strip: one tick per point, easy to read for straights
    return svg(CARD_W, CARD_H, body)


def ace_card(s: int) -> str:
    cx, cy = 58.5, 82
    rays = []
    for i in range(16):
        a0, a1 = (i - 0.22) * math.pi / 8, (i + 0.22) * math.pi / 8
        rays.append(f"M{cx},{cy} L{cx + 90 * math.cos(a0):.1f},{cy + 90 * math.sin(a0):.1f} "
                    f"L{cx + 90 * math.cos(a1):.1f},{cy + 90 * math.sin(a1):.1f} Z")
    body = card_frame() + index(12, s)
    body += (f'<clipPath id="f"><rect x="37" y="14" width="43" height="136"/></clipPath>'
             f'<g clip-path="url(#f)"><path d="{" ".join(rays)}" fill="{B}"/></g>')
    body += deco_frame(33, 10, 84, 154)
    body += f'<circle cx="{cx}" cy="{cy}" r="25" fill="{W}" stroke="{B}" stroke-width="3"/>'
    body += f'<circle cx="{cx}" cy="{cy}" r="20.5" fill="none" stroke="{B}" stroke-width="1"/>'
    body += suit(s, cx, cy + 1, 28, sw=3.5)
    return svg(CARD_W, CARD_H, body)


def face_features(cx, cy, rx, ry, lit_eye=True, lashes=False) -> str:
    """White face with the left half in shadow (film-noir key light from the right)."""
    out = [f'<clipPath id="face"><ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}"/></clipPath>',
           f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{W}" stroke="{W}" stroke-width="1.5"/>',
           f'<path clip-path="url(#face)" d="M{cx - rx - 2},{cy - ry - 2} L{cx - 1},{cy - ry - 2} '
           f'Q{cx + 3},{cy} {cx - 1},{cy + ry + 2} L{cx - rx - 2},{cy + ry + 2} Z" fill="{B}"/>']
    # shadow-side eye glint, lit-side eye, nose edge, mouth
    out.append(f'<rect x="{cx - rx * 0.55}" y="{cy - 2}" width="4" height="1.6" fill="{W}"/>')
    if lit_eye:
        out.append(f'<path d="M{cx + 2.5},{cy - 1.5} q3,-2.5 6,0 q-3,2 -6,0 Z" fill="{B}"/>')
        out.append(f'<rect x="{cx + 2.5}" y="{cy - 5.5}" width="6" height="1.6" fill="{B}"/>')
        if lashes:
            out.append(f'<path d="M{cx + 8},{cy - 2} l2.5,-2 M{cx + 7},{cy - 3} l1.5,-2.5" stroke="{B}" stroke-width="1.2"/>')
    out.append(f'<path d="M{cx + 1},{cy + 1} l2,6 l-2.5,0.5" fill="none" stroke="{B}" stroke-width="1.3"/>')
    return "".join(out)


def blinds() -> str:
    """Light through venetian blinds on the dark portrait backdrop."""
    return "".join(f'<line x1="{x}" y1="0" x2="{x - 60}" y2="98" stroke="{W}" stroke-width="1.6"/>' for x in range(60, 150, 9))


