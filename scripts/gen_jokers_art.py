def court_card(rank: int, s: int) -> str:
    art = {9: jack, 10: queen, 11: king}[rank](s)
    px, py, pw, ph = 32, 6, 76, 98
    body = card_frame() + index(rank, s)
    body += (f'<clipPath id="panel"><rect x="0" y="0" width="{pw}" height="{ph}"/></clipPath>'
             f'<rect x="{px - 2}" y="{py - 2}" width="{pw + 4}" height="{ph + 4}" fill="{B}"/>'
             f'<g transform="translate({px} {py})" clip-path="url(#panel)">{blinds()}'
             f'<g transform="translate(38 62) scale(1.3) translate(-38 -62)">{art}</g></g>'
             f'<rect x="{px + 1.5}" y="{py + 1.5}" width="{pw - 3}" height="{ph - 3}" fill="none" stroke="{W}" stroke-width="1"/>')
    # big suit with deco rules in the free lower-left corner
    body += suit(s, 45, 132, 30, sw=3.5)
    body += (f'<path d="M8,129.5 H26 M8,134.5 H26 M64,129.5 H82 M64,134.5 H82" stroke="{B}" stroke-width="1.5"/>'
             f'<path d="M26,127 l4,5 l-4,5 Z M64,127 l-4,5 l4,5 Z" fill="{B}"/>')
    return svg(CARD_W, CARD_H, body)


def card_back() -> str:
    body = f'<rect x="1" y="1" width="{CARD_W - 2}" height="{CARD_H - 2}" rx="8" fill="{B}" stroke="{B}" stroke-width="2"/>'
    body += f'<rect x="6.5" y="6.5" width="{CARD_W - 13}" height="{CARD_H - 13}" rx="4" fill="none" stroke="{W}" stroke-width="1.5"/>'
    body += '<clipPath id="in"><rect x="10" y="10" width="96" height="144"/></clipPath><g clip-path="url(#in)">'
    # nested chevrons radiating from the centre line
    for i in range(-2, 14):
        y = 10 + i * 12
        body += f'<path d="M10,{y} L58,{y + 24} L106,{y}" fill="none" stroke="{W}" stroke-width="1.6"/>'
    body += "</g>"
    body += f'<rect x="10.5" y="10.5" width="95" height="143" fill="none" stroke="{W}" stroke-width="1"/>'
    body += f'<circle cx="58" cy="82" r="21" fill="{B}" stroke="{W}" stroke-width="2"/>'
    body += f'<circle cx="58" cy="82" r="16" fill="{W}"/>'
    body += jester_mask(58, 83, 13)
    return svg(CARD_W, CARD_H, body)


def jester_mask(cx, cy, r, ink=B, paper=W) -> str:
    """Three-point jester cap over a grinning mask, fits a circle of radius r."""
    k = r / 13
    return (f'<g transform="translate({cx} {cy}) scale({k})">'
            f'<path d="M-11,-2 Q-14,-12 -6,-15 L-2,-7 L0,-16 L2,-7 L6,-15 Q14,-12 11,-2 Z" fill="{ink}"/>'
            f'<circle cx="-6" cy="-15" r="2" fill="{ink}"/><circle cx="0" cy="-16" r="2" fill="{ink}"/><circle cx="6" cy="-15" r="2" fill="{ink}"/>'
            f'<path d="M-10,-2 Q-10,12 0,12 Q10,12 10,-2 Z" fill="{ink}"/>'
            f'<path d="M-7,1 l4,-2 l1,3 Z M7,1 l-4,-2 l-1,3 Z" fill="{paper}"/>'
            f'<path d="M-6,5 Q0,10 6,5" fill="none" stroke="{paper}" stroke-width="1.8"/></g>')


