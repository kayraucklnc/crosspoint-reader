#!/usr/bin/env python3
"""Render the Noir Jokers art (original, drawn here as SVG) into the game's SD-card pack.

The converted art is NOT committed; run this script to generate it:

    uv run --with resvg-py --with numpy --with pillow --with fonttools \\
        scripts/gen_jokers_art.py OUT_DIR [OUT_DIR ...] [--preview PNG]

e.g. OUT_DIR = fs_/.crosspoint/games/jokers (simulator) or <sd-extra>/.crosspoint/games/jokers.
--preview writes a 1:1 contact sheet decoded from the pack (transparent = gray).

Typography uses Abril Fatface and Limelight (SIL Open Font License), fetched from
github.com/google/fonts at run time; without network a serif system font is used.

1-bit conversion renders at 3x and reduces each 3x3 block like gen_avatars.py:
mostly-dark blocks are black, pure black/white blocks threshold, blocks with
mid-tone fills get a 4x4 ordered dither and mostly-transparent blocks stay
transparent. The art is designed in pure black and white, so dithering is rare.

Output: art.bin + NOTICE.txt. art.bin layout (little endian):
  "JKA1", u16 assetCount, u16 reserved (0),
  per asset: u32 offset (absolute), u32 length, u16 w, u16 h (length 0 = empty),
  then RLE data: bytes (state << 6) | (run - 1), run 1..64, over the asset's w*h
  pixels row-major (runs may cross rows); state 0 = transparent, 1 = white, 2 = black.

Asset ids (115):
  0 card back 116x164; 1 + suit*13 + rank card faces 116x164 (rank 0..12 = 2..10,J,Q,K,A;
  suit 0 spades, 1 hearts, 2 clubs, 3 diamonds); 53..77 jokers 84x112; 78 small blind,
  79 big blind, 80..89 boss blinds (96x96); 90..98 planets 72x72; 99 title 528x300;
  100..114 score glyphs "0123456789,x=+$" (black on transparent, shared height/baseline).
"""

