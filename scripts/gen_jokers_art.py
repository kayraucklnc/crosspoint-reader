def pack(grids: list) -> bytes:
    header = b"JKA1" + struct.pack("<HH", len(grids), 0)
    base = len(header) + 12 * len(grids)
    index, blob = bytearray(), bytearray()
    for g in grids:
        data = rle(g)
        index += struct.pack("<IIHH", base + len(blob), len(data), g.shape[1], g.shape[0])
        blob += data
    return header + bytes(index) + bytes(blob)


def decode(data: bytes) -> list:
    count = struct.unpack_from("<H", data, 4)[0]
    out = []
    for i in range(count):
        off, n, w, h = struct.unpack_from("<IIHH", data, 8 + 12 * i)
        px = []
        for b in data[off : off + n]:
            px += [b >> 6] * ((b & 63) + 1)
        out.append(np.array(px[: w * h], dtype=np.uint8).reshape(h, w))
    return out


def preview(data: bytes, path: Path) -> None:
    grids = decode(data)
    sheet_w, pad, label = 1200, 10, 12
    x = y = pad
    row_h, places = 0, []
    for g in grids:
        h, w = g.shape
        if x + w + pad > sheet_w:
            x, y, row_h = pad, y + row_h + label + pad, 0
        places.append((x, y))
        x += w + pad
        row_h = max(row_h, h)
    img = Image.new("L", (sheet_w, y + row_h + label + pad), 150)
    draw = ImageDraw.Draw(img)
    for i, (g, (px, py)) in enumerate(zip(grids, places)):
        tile = np.full(g.shape, 150, np.uint8)
        tile[g == 1], tile[g == 2] = 255, 0
        img.paste(Image.fromarray(tile), (px, py + label))
        draw.text((px, py), str(i), fill=0)
    img.save(path)


def per_category(data: bytes) -> dict:
    count = struct.unpack_from("<H", data, 4)[0]
    sizes = [struct.unpack_from("<IIHH", data, 8 + 12 * i)[1] for i in range(count)]
    spans = {"card back": (0, 1), "cards": (1, 53), "jokers": (53, 78), "blinds": (78, 90), "planets": (90, 99),
             "title": (99, 100), "glyphs": (100, 115)}
    return {k: sum(sizes[a:b]) for k, (a, b) in spans.items()}


def main() -> int:
    args = sys.argv[1:]
    preview_path = None
    if "--preview" in args:
        i = args.index("--preview")
        preview_path = Path(args[i + 1])
        del args[i : i + 2]
    outs = [Path(p) for p in args]
    if not outs and not preview_path:
        print(__doc__)
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        fonts = fetch_fonts(Path(tmp))
        data = pack(build(fonts))
    assert struct.unpack_from("<H", data, 4)[0] == 115
    for out in outs:
        out.mkdir(parents=True, exist_ok=True)
        (out / "art.bin").write_bytes(data)
        (out / "NOTICE.txt").write_text(NOTICE)
        print(f"wrote {out / 'art.bin'} ({len(data)} bytes)")
    print(", ".join(f"{k} {v}" for k, v in per_category(data).items()))
    if preview_path:
        preview(data, preview_path)
        print(f"preview {preview_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
